export type Row = Record<string, unknown>

export interface Queryable {
  /** Runs one parameterised statement (`$1`, `$2`…) and returns its rows. */
  query<T = Row>(text: string, params?: unknown[]): Promise<T[]>
}

interface Driver extends Queryable {
  /** Runs several statements without parameters. */
  exec(text: string): Promise<void>
  transaction<T>(fn: (q: Queryable) => Promise<T>): Promise<T>
  close(): Promise<void>
}

/* ------------------------------- Drivers ------------------------------- */

async function postgresDriver(url: string): Promise<Driver> {
  const { default: postgres } = await import('postgres')
  const sql = postgres(url, {
    // Supabase's transaction pooler does not support prepared statements.
    prepare: false,
    max: Number(process.env.DATABASE_POOL_SIZE) || 5,
    idle_timeout: 20,
    connect_timeout: 15,
    onnotice: () => {},
  })
  const run =
    <T>(s: Pick<Sql, 'unsafe'>) =>
    (text: string, params: unknown[] = []) =>
      s.unsafe(text, params as never[]) as unknown as Promise<T[]>
  return {
    query: <T>(text: string, params?: unknown[]) => run<T>(sql)(text, params),
    exec: async (text) => {
      await sql.unsafe(text).simple()
    },
    transaction: async <T>(fn: (q: Queryable) => Promise<T>) =>
      (await sql.begin((tx) => fn({ query: <U>(text: string, params?: unknown[]) => run<U>(tx)(text, params) }))) as T,
    close: () => sql.end({ timeout: 5 }),
  }
}

async function pgliteDriver(dir: string): Promise<Driver> {
  const { PGlite } = await import('@electric-sql/pglite')
  fs.mkdirSync(dir, { recursive: true })
  const pg = await PGlite.create(dir)
  type Q = Pick<typeof pg, 'query'>
  const run = (q: Q) => async (text: string, params?: unknown[]) => (await q.query(text, params)).rows
  return {
    query: <T>(text: string, params?: unknown[]) => run(pg)(text, params) as Promise<T[]>,
    exec: async (text) => {
      await pg.exec(text)
    },
    transaction: (fn) =>
      pg.transaction((tx) =>
        fn({ query: <U>(text: string, params?: unknown[]) => run(tx)(text, params) as Promise<U[]> }),
      ),
    close: () => pg.close(),
  }
}

/* ------------------------------ Migrations ----------------------------- */

async function migrate(driver: Driver) {
  await driver.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
    version    integer PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
  )`)
  const latest = async (q: Queryable) =>
    (await q.query<{ v: number }>('SELECT COALESCE(MAX(version), 0)::int AS v FROM schema_migrations'))[0]!.v
  if ((await latest(driver)) >= MIGRATIONS.length) return
  await driver.transaction(async (tx) => {
    // Serialises concurrent cold starts: only one instance applies the migrations.
    await tx.query('SELECT pg_advisory_xact_lock(724519)')
    for (let v = await latest(tx); v < MIGRATIONS.length; v++) {
      for (const statement of splitStatements(MIGRATIONS[v]!)) await tx.query(statement)
      await tx.query('INSERT INTO schema_migrations (version) VALUES ($1)', [v + 1])
    }
  })
}

/** Splits a migration on top-level semicolons (migrations contain no functions or string literals with `;`). */
function splitStatements(sql: string): string[] {
  return sql
    .replace(/--[^\n]*/g, '')
    .split(';')
    .map((s) => s.trim())
    .filter(Boolean)
}

/* -------------------------------- Access ------------------------------- */

const globalForDb = globalThis as unknown as { __soleilDb?: Promise<Driver> }

async function open(): Promise<Driver> {
  const url = process.env.DATABASE_URL
  const driver = url ? await postgresDriver(url) : await pgliteDriver(path.join(dataDir(), 'pglite'))
  await migrate(driver)
  return driver
}

/** One connection pool per process (and across dev hot reloads); a failed open is retried next time. */
function driver(): Promise<Driver> {
  if (!globalForDb.__soleilDb) {
    globalForDb.__soleilDb = open().catch((error: unknown) => {
      globalForDb.__soleilDb = undefined
      throw error
    })
  }
  return globalForDb.__soleilDb
}

export async function query<T = Row>(text: string, params?: unknown[]): Promise<T[]> {
  return (await driver()).query<T>(text, params)
}

export async function one<T = Row>(text: string, params?: unknown[]): Promise<T | undefined> {
  return (await query<T>(text, params))[0]
}

export async function transaction<T>(fn: (q: Queryable) => Promise<T>): Promise<T> {
  return (await driver()).transaction(fn)
}

export async function schemaVersion(): Promise<number> {
  return (await one<{ v: number }>('SELECT COALESCE(MAX(version), 0)::int AS v FROM schema_migrations'))!.v
}

export const LATEST_SCHEMA_VERSION = MIGRATIONS.length

/** Closes the pool (scripts and tests). */
export async function closeDb() {
  const current = globalForDb.__soleilDb
  globalForDb.__soleilDb = undefined
  if (current) await (await current).close()
}

/** Timestamps come back as `Date` objects; the app exchanges ISO strings. */
export function iso(value: unknown): string {
  return value instanceof Date ? value.toISOString() : String(value)
}
